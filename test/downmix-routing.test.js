for (const [source, target, matrix] of cases) {
  test(`independent speaker routing ${source} → ${target}`, async () => {
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'audiority-routing-'));
    try {
      const channels = matrix[0].length, file = path.join(directory, 'decoded.f64');
      // One source speaker at a time, with silence at boundaries. No encoder loss.
      const expressions = Array.from({ length: channels }, (_, i) => `0.25*between(t\\,${i * .1 + .02}\\,${i * .1 + .08})`).join('|');
      const filters = audioFilters({ action: 'encode', downmix: true, sourceLayout: source, layout: target });
      await run(toolPaths().ffmpeg, ['-v','error','-f','lavfi','-i',`aevalsrc=${expressions}:s=48000:c=${source}`,
        '-t',String(channels * .1),'-af',filters.join(','),'-c:a','pcm_f64le','-f','f64le',file]);
      const bytes = await fs.readFile(file);
      for (let input = 0; input < channels; input++) for (let output = 0; output < matrix.length; output++) {
        const frame = Math.round((input * .1 + .05) * 48000);
        const actual = bytes.readDoubleLE((frame * matrix.length + output) * 8) / .25;
        assert.ok(Math.abs(actual - matrix[output][input]) < 0.00001, `input ${input} output ${output}: ${actual} != ${matrix[output][input]}`);
      }
    } finally { await fs.rm(directory, { recursive: true, force: true }); }
  });
}

test('legacy front-6.1 rules load but cannot silently create a center-equipped output', () => {
  for (const target of ['5.1(side)', '3.1']) {
    const profile = resolveProfile({ ...defaultSettings(), advanced: true, allowDownmix: true, downmixRules: [{ source: '6.1(front)', target }] });
    const track = planTrack({ index: 0, codec_name: 'flac', channels: 7, channel_layout: '6.1(front)', sample_rate: '48000' }, {}, profile);
    assert.equal(track.action, 'copy'); assert.equal(track.compatibility, 'unresolved');
    assert.match(track.reason, /no discrete center/);
    assert.throws(() => audioFilters({ action: 'encode', downmix: true, sourceLayout: '6.1(front)', layout: target }), /no discrete center/);
  }
  assert.equal(audioFilters({ action: 'encode', downmix: true, sourceLayout: '6.1(front)', layout: 'stereo' }).length, 1);
});

for (const codec of ['ac3', 'dts']) {
  test(`decoded ${codec} peaks remain bounded for correlated 0.9-peak 7.1 with optional processing`, { timeout: 60000 }, async () => {
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'audiority-mix-peaks-'));
    try {
      const tools = toolPaths(), engine = new Engine(tools), input = path.join(directory, 'source.mkv');
      await run(tools.ffmpeg, ['-v','error','-f','lavfi','-i',`aevalsrc=${Array(8).fill('0.9*sin(2*PI*100*t)').join('|')}:s=48000:c=7.1`, '-t','3','-c:a','flac',input]);
      engine.setProfile(resolveProfile({ ...defaultSettings(), advanced: true, allowed: [codec], pathConfirmed: true,
        pathCodecs: [codec], passthrough: 'enabled', allowDownmix: true, downmixRules: [{ source: '7.1', target: '5.1(side)' }] }));
      const item = await engine.inspect(input);
      for (const [dialogueBoost, normalizeVolume] of [[false,false],[true,false],[false,true],[true,true]]) {
        const result = await engine.convert(item, directory, { preferences: { ...preferencesDefaults(), dialogueBoost, normalizeVolume } });
        const raw = path.join(directory, `decoded-${dialogueBoost}-${normalizeVolume}.f32`);
        await run(tools.ffmpeg, ['-v','error','-i',result.output,'-map','0:a:0','-c:a','pcm_f32le','-f','f32le',raw]);
        const bytes = await fs.readFile(raw); let peak = 0;
        for (let offset = 0; offset < bytes.length; offset += 4) {
          const value = bytes.readFloatLE(offset); assert.ok(Number.isFinite(value)); peak = Math.max(peak, Math.abs(value));
        }
        assert.ok(peak > .1 && peak < 1, `${codec} boost=${dialogueBoost} norm=${normalizeVolume}: peak ${peak}`);
        assert.match(result.conversionReport, /rematrix_maxval=1:lfe_mix_level=0/);
        assert.equal(result.conversionReport.includes('FC=1.5*FC'), dialogueBoost);
        assert.equal(result.conversionReport.includes('dynaudnorm='), normalizeVolume);
      }
    } finally { await fs.rm(directory, { recursive: true, force: true }); }
  });
}