test('processing is encode-only and report does not claim filters on retained originals', () => {
  const { conversionReport } = require('../src/conversion-report');
  const preferences = { dialogueBoost: true, normalizeVolume: true };
  for (const action of ['copy', 'extract']) assert.deepEqual(audioFilters({ action, downmix: true }, preferences), []);
  const source = { index: 3, codec_type: 'audio', codec_name: 'flac', channels: 8, channel_layout: '7.1' };
  const track = { index: 3, action: 'encode', codec: 'dca', keepOriginal: true, downmix: true, sourceLayout: '7.1', layout: '5.1(side)' };
  const report = conversionReport({ probe: { streams: [source] }, plan: { tracks: [track] } },
    { streams: [source, { index: 4, codec_type: 'audio', codec_name: 'dts', channels: 6, channel_layout: '5.1(side)' }] }, preferences);
  assert.match(report, /retained original[^\n]*\n  Filters: none/);
  assert.equal(report.split('aresample=').length - 1, 1);
  assert.equal(report.split('dynaudnorm=').length - 1, 1);
  assert.match(report, /dedicated LFE omitted only when output has no LFE/);
});

